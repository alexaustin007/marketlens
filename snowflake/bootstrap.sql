CREATE DATABASE IF NOT EXISTS MARKETLENS_DEV;
CREATE SCHEMA IF NOT EXISTS MARKETLENS_DEV.RAW;
CREATE SCHEMA IF NOT EXISTS MARKETLENS_DEV.STAGING;
CREATE SCHEMA IF NOT EXISTS MARKETLENS_DEV.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS MARKETLENS_DEV.MARTS;

CREATE STAGE IF NOT EXISTS MARKETLENS_DEV.RAW.MARKETLENS_RAW_STAGE;

CREATE TABLE IF NOT EXISTS MARKETLENS_DEV.RAW.HISTORICAL_PRICES (
    PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE NETWORK RULE IF NOT EXISTS MARKETLENS_DEV.RAW.TWELVEDATA_API_RULE
    MODE = EGRESS
    TYPE = HOST_PORT
    VALUE_LIST = ('api.twelvedata.com');

CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS MARKETLENS_TWELVEDATA_ACCESS
    ALLOWED_NETWORK_RULES = (MARKETLENS_DEV.RAW.TWELVEDATA_API_RULE)
    ALLOWED_AUTHENTICATION_SECRETS = (MARKETLENS_DEV.RAW.TWELVEDATA_API_KEY)
    ENABLED = TRUE;
